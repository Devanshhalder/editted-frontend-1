  /// Returns a translated string for the currently selected language.
  ///
  /// If a key is missing in a language, English is safely used as fallback.
  static String text(
      String language,
      String key,
      ) {
    final normalizedLanguage = _normalizeLanguage(language);
    final selected = _translations[normalizedLanguage];
    final english = _translations['English']!;

    return _aiErrorTranslations[normalizedLanguage]?[key] ??
        _moreTranslations[normalizedLanguage]?[key] ??
        _additionalTranslations[normalizedLanguage]?[key] ??
        _shortTranslations[normalizedLanguage]?[key] ??
        selected?[key] ??
        _moreTranslations['English']?[key] ??
        _additionalTranslations['English']?[key] ??
        _shortTranslations['English']?[key] ??
        english[key] ??
        key;
  }

  static String _normalizeLanguage(String language) {
    switch (language) {
      case 'हिंदी':
        return 'Hindi';
      case 'বাংলা':
        return 'Bengali';
      case 'தமிழ்':
        return 'Tamil';
      case 'తెలుగు':
        return 'Telugu';
      case 'मराठी':
        return 'Marathi';
      case 'ગુજરાતી':
        return 'Gujarati';
      case 'ಕನ್ನಡ':
        return 'Kannada';
      default:
        return language;
    }
  }

  /// Convenience helper for widgets.
  static String of(
      BuildContext context,
      String key,
      ) {
    return text(AppScope.of(context).language, key);
  }

  /// Returns the translated display name of a language.
  static String languageName(
      String currentLanguage,
      String language,
      ) {
    final key = switch (language) {
      'English' => 'english',
      'Hindi' => 'hindi',
      'Bengali' => 'bengali',
      'Tamil' => 'tamil',
      'Telugu' => 'telugu',
      'Marathi' => 'marathi',
      'Gujarati' => 'gujarati',
      'Kannada' => 'kannada',
      _ => 'english',
    };

    return text(currentLanguage, key);
  }
}

